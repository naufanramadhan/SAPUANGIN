function [p, c] = read_study_inputs(root)
% MATLAB reads Excel directly; Octave reads a freshly exported JSON snapshot.
workbook = fullfile(root, 'input', 'FSAE_VD_3_KASAR .xlsx');
if exist('OCTAVE_VERSION', 'builtin')
    snapshot = fullfile(root, 'input', 'study_inputs.json');
    assert(isfile(snapshot), ['Export workbook first: python3 tools/' ...
        'export_workbook.py']);
    d = jsondecode(fileread(snapshot));
    assert(strcmp(hash('sha256',fileread(workbook)),d.workbook_sha256), ...
        'Workbook content changed. Re-export study_inputs.json.');
    info = dir(workbook);
    % Content identity is authoritative; timestamps can change after ZIP extraction.
    assert(abs(info.bytes - d.workbook_size_bytes) < 1, ...
        'Workbook size changed. Re-export study_inputs.json.');
    values = d.baseline(:);
    c = d.config;
else
    raw = readcell(workbook, 'Sheet', '02_INPUT_VARIABLES', ...
        'Range', 'E4:E58', 'UseExcel', false);
    values = zeros(55,1);
    for i = 1:55
        assert(isnumeric(raw{i}) && isscalar(raw{i}) && isfinite(raw{i}), ...
            'Baseline E%d must be a finite number.', i+3);
        values(i) = raw{i};
    end
    raw = readcell(workbook, 'Sheet', '06_SIMULATION_CONFIG', ...
        'Range', 'A2:B200', 'UseExcel', false);
    c = struct();
    for i = 1:size(raw,1)
        key = raw{i,1};
        if ~(ischar(key) || (isstring(key) && ~ismissing(key))), continue; end
        key = char(key);
        if isempty(key), continue; end
        assert(isvarname(key) && ~isfield(c,key), ...
            'Invalid or duplicate config key: %s', key);
        c.(key) = raw{i,2};
        if isstring(c.(key)), c.(key) = char(c.(key)); end
    end
end
names = {'g','m_total','WD_f','m_uf','m_ur','T_f','T_r','L', ...
    'h','h_uf','h_ur','z_RF','z_RR','L_lower_f','L_upper_f', ...
    'Ratio_UL_f','W_inboard_lf','gamma_0f','theta_KPI_f', ...
    'theta_caster','d_KPI_f','W_offset_f','R_scrub_f', ...
    'L_lower_r','L_upper_r','Ratio_UL_r','W_inboard_lr', ...
    'gamma_0r','Toe_r','W_offset_r','L_halfshaft','theta_CV_max', ...
    'R_corner','K_sf','IR_f','K_arbf','K_sr','IR_r','K_arbr', ...
    'r_f','K_tf','mu_0f','dmu_dFz_f','F_z0f','r_r','K_tr', ...
    'mu_0r','dmu_dFz_r','F_z0r','OD','t_wall','E_modulus', ...
    'Sigma_y','L_stub','A_y'};
assert(numel(values)==numel(names) && all(isfinite(values)));
for i = 1:numel(names), p.(names{i}) = values(i); end

required = {'front_track_min_mm','front_track_max_mm','track_step_mm', ...
    'rear_track_delta_mode','tire_section_width_mm','cone_safety_margin_m', ...
    'max_speed_kph','max_accel_mps2','max_brake_mps2', ...
    'cornering_safety_factor','curvature_smoothing_points', ...
    'speed_profile_iterations','track_declared_length_m','track_width_m', ...
    'skidpad_inner_diameter_m','skidpad_lane_width_m', ...
    'skidpad_timed_laps_per_direction','skidpad_max_steer_deg', ...
    'motion_ratio_convention','path_scale_mode','speed_convergence_mps', ...
    'run_sensitivity','sensitivity_mu_fraction','sensitivity_h_mm'};
for i=1:numel(required)
    assert(isfield(c,required{i}), 'Missing config: %s',required{i});
    val = c.(required{i});
    if isnumeric(val), assert(isscalar(val) && isfinite(val)); end
end
assert(p.g>0 && p.m_total>0 && p.WD_f>0 && p.WD_f<1);
assert(p.m_uf>=0 && p.m_ur>=0 && p.h>0 && p.h_uf>=0 && p.h_ur>=0);
assert(all([p.T_f,p.T_r,p.L,p.K_sf,p.K_sr,p.IR_f,p.IR_r,p.K_tf,p.K_tr]>0));
assert(all([p.K_arbf,p.K_arbr]>=0));
assert(all([p.mu_0f,p.mu_0r,p.F_z0f,p.F_z0r]>0));
assert(p.dmu_dFz_f<=0 && p.dmu_dFz_r<=0, ...
    'This screening model requires non-positive tyre load sensitivity.');
assert(c.front_track_min_mm>0 && c.track_step_mm>0 && ...
    c.front_track_max_mm>=c.front_track_min_mm);
assert(c.front_track_min_mm<=p.T_f && c.front_track_max_mm>=p.T_f, ...
    'Sweep must contain the measured baseline track.');
assert(strcmp(c.rear_track_delta_mode,'fixed'), ...
    'This front-only study requires rear_track_delta_mode = fixed.');
assert(any(strcmp(c.motion_ratio_convention, ...
    {'spring_over_wheel','wheel_over_spring'})));
assert(any(strcmp(c.path_scale_mode,{'raw','uniform_to_declared_length'})));
assert(c.track_width_m>0 && c.tire_section_width_mm>0 && ...
    c.cone_safety_margin_m>=0 && 2*c.cone_safety_margin_m<c.track_width_m);
assert(c.cornering_safety_factor>0 && c.cornering_safety_factor<1);
assert(all([c.max_speed_kph,c.max_accel_mps2,c.max_brake_mps2, ...
    c.skidpad_inner_diameter_m,c.skidpad_lane_width_m, ...
    c.track_declared_length_m,c.speed_convergence_mps]>0));
assert(c.skidpad_max_steer_deg>0 && c.skidpad_max_steer_deg<90);
assert(c.skidpad_timed_laps_per_direction>=1 && ...
    c.skidpad_timed_laps_per_direction==round(c.skidpad_timed_laps_per_direction));
assert(c.curvature_smoothing_points>=3 && ...
    c.curvature_smoothing_points==round(c.curvature_smoothing_points));
assert(c.speed_profile_iterations>=1 && ...
    c.speed_profile_iterations==round(c.speed_profile_iterations));
assert(any(c.run_sensitivity==[0,1]) && c.sensitivity_mu_fraction>=0 && ...
    c.sensitivity_mu_fraction<1 && c.sensitivity_h_mm>=0 && ...
    c.sensitivity_h_mm<p.h);
p.W_total = p.m_total*p.g;
p.m_sf = p.m_total*p.WD_f-p.m_uf;
p.m_sr = p.m_total*(1-p.WD_f)-p.m_ur;
assert(p.m_sf>0 && p.m_sr>0, 'Unsprung masses exceed axle masses.');
p.m_s = p.m_sf+p.m_sr;
p.h_s = (p.m_total*p.h-p.m_uf*p.h_uf-p.m_ur*p.h_ur)/p.m_s;
p.z_RA = p.z_RF+(p.z_RR-p.z_RF)*p.m_sr/p.m_s;
assert(p.h_s>p.z_RA && p.z_RF>=0 && p.z_RR>=0, ...
    'Model requires sprung CG above a nonnegative roll axis.');
p.M_R_per_g = p.m_s*p.g*(p.h_s-p.z_RA)/1000;
end
